import turtle as t
import time
#도
t.shape("turtle")
t.speed(10)
t.penup()
t.goto(-200,50)
t.speed(1)
t.pendown()
t.forward(50)
t.goto(-200,50)
t.right(90)
t.forward(50)
t.goto(-200,0)
t.left(90)
t.forward(50)
t.goto(-175,0)
t.right(90)
t.forward(25)
t.goto(-200,-25)
t.left(90)
t.forward(50)

#미
t.penup()
t.goto(-100,0)
t.pendown()
for i in range(4):
    t.forward(50)
    t.left(90)
t.penup()
t.goto(0,75)
t.pendown()
t.right(90)
t.forward(100)

#ㄹ
t.penup()
t.goto(100,100)
t.pendown()
t.left(90)
t.forward(50)
t.right(90)
t.forward(25)
t.right(90)
t.forward(50)
t.left(90)
t.forward(25)
t.left(90)
t.forward(50)

#ㅏ
t.penup()
t.goto(200,100)
t.pendown()
t.right(90)
t.forward(50)
t.goto(200,75)
t.left(90)
t.forward(25)

#ㄴ
t.penup()
t.goto(100,0)
t.right(90)
t.pendown()
t.forward(50)
t.left(90)
t.forward(50)

for i in range(4):
    t.color("red")
    time.sleep(0.1)
    t.color("blue")
    time.sleep(0.1)
    t.color("yellow")
t.hideturtle()
time.sleep(1)
t.textinput("끝", "엔터를 누르세요")
t.bye()
